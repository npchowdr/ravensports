from django.db import models

class PlayerAdvancedStats(models.Model):
    Rank = models.IntegerField()
    Player = models.CharField(max_length=100)
    Position = models.CharField(max_length=10)
    Age = models.IntegerField()
    Team = models.CharField(max_length=5)
    GamesPlayed = models.IntegerField()
    MinutesPlayed = models.FloatField()
    PlayerEfficiencyRating = models.FloatField(null=True)
    TrueShootingPercentage = models.FloatField(null=True)
    ThreePointAttemptRate = models.FloatField(null=True)
    FreeThrowAttemptRate = models.FloatField(null=True)
    OffensiveReboundPercentage = models.FloatField(null=True)
    DefensiveReboundPercentage = models.FloatField(null=True)
    TotalReboundPercentage = models.FloatField(null=True)
    AssistPercentage = models.FloatField(null=True)
    StealPercentage = models.FloatField(null=True)
    BlockPercentage = models.FloatField(null=True)
    TurnoverPercentage = models.FloatField(null=True)
    UsagePercentage = models.FloatField(null=True)
    OffensiveWinShares = models.FloatField(null=True)
    DefensiveWinShares = models.FloatField(null=True)
    WinShares = models.FloatField(null=True)
    WinSharesPer48 = models.FloatField(null=True)
    OffensiveBoxPlusMinus = models.FloatField(null=True)
    DefensiveBoxPlusMinus = models.FloatField(null=True)
    BoxPlusMinus = models.FloatField(null=True)
    ValueOverReplacementPlayer = models.FloatField(null=True)
    Year = models.IntegerField()
    objects = models.Manager()
