from django.db import models

class PlayerPer100Stats(models.Model):
    Rank = models.IntegerField()
    Player = models.CharField(max_length=100)
    Position = models.CharField(max_length=10)
    Age = models.IntegerField()
    Team = models.CharField(max_length=5)
    GamesPlayed = models.IntegerField()
    GamesStarted = models.FloatField(null=True)
    MinutesPlayed = models.FloatField()
    FieldGoalsMade = models.FloatField(null=True)
    FieldGoalsAttempted = models.FloatField(null=True)
    FieldGoalPercentage = models.FloatField(null=True)
    ThreePointersMade = models.FloatField(null=True)
    ThreePointersAttempted = models.FloatField(null=True)
    ThreePointPercentage = models.FloatField(null=True)
    TwoPointersMade = models.FloatField(null=True)
    TwoPointersAttempted = models.FloatField(null=True)
    TwoPointPercentage = models.FloatField(null=True)
    FreeThrowsMade = models.FloatField(null=True)
    FreeThrowsAttempted = models.FloatField(null=True)
    FreeThrowPercentage = models.FloatField(null=True)
    OffensiveRebounds = models.FloatField(null=True)
    DefensiveRebounds = models.FloatField(null=True)
    TotalRebounds = models.FloatField(null=True)
    Assists = models.FloatField(null=True)
    Steals = models.FloatField(null=True)
    Blocks = models.FloatField(null=True)
    Turnovers = models.FloatField(null=True)
    PersonalFouls = models.FloatField(null=True)
    Points = models.FloatField(null=True)
    OffensiveRating = models.IntegerField(null=True)
    DefensiveRatings = models.IntegerField(null=True)
    Year = models.IntegerField()
